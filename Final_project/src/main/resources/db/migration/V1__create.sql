CREATE TABLE IF NOT EXISTS PRODUCT(
   PRODUCT_ID SERIAL NOT NULL,
   DESCRIPTION CHARACTER VARYING(255) NOT NULL,
   COST INTEGER NOT NULL,
   QUANTITY INTEGER NOT NULL,
   CATEGORY CHARACTER VARYING(50) NOT NULL,
   CONSTRAINT PRODUCT_ID_PK PRIMARY KEY (PRODUCT_ID)
);

CREATE TABLE IF NOT EXISTS CUSTOMER(
   CUSTOMER_ID SERIAL NOT NULL,
   FIRST_NAME CHARACTER VARYING(50) NOT NULL,
   LAST_NAME CHARACTER VARYING(50) NOT NULL,
   PHONE_NUMBER CHARACTER VARYING(11) NOT NULL,
   EMAIL CHARACTER VARYING(255) NOT NULL,
   CONSTRAINT CUSTOMER_ID_PK PRIMARY KEY (CUSTOMER_ID)
);

CREATE TABLE IF NOT EXISTS ORDERS(
   ORDER_ID SERIAL NOT NULL,
   PRODUCT_ID BIGINT NOT NULL,
   CUSTOMER_ID BIGINT NOT NULL,
   ORDER_DATE DATE NOT NULL,
   QUANTITY INTEGER NOT NULL,
   STATUS SMALLINT NOT NULL,
   CONSTRAINT ORDER_ID_PK PRIMARY KEY (ORDER_ID)
);

CREATE TABLE IF NOT EXISTS ORDER_STATUS(
   STATUS_ID SERIAL NOT NULL,
   NAME_STATUS CHARACTER VARYING(50) NOT NULL,
   CONSTRAINT STATUS_ID_PK PRIMARY KEY (STATUS_ID)
);

ALTER TABLE ORDERS ADD CONSTRAINT ORDERS_PRODUCT_ID_FK FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT(PRODUCT_ID) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE ORDERS ADD CONSTRAINT ORDERS_CUSTOMER_ID_FK FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID) ON DELETE CASCADE ON UPDATE CASCADE;
ALTER TABLE ORDERS ADD CONSTRAINT ORDERS_STATUS_FK FOREIGN KEY (STATUS) REFERENCES ORDER_STATUS(STATUS_ID) ON DELETE CASCADE ON UPDATE CASCADE;
